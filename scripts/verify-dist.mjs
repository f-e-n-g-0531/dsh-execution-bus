import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { lstatSync, readdirSync, readFileSync } from "node:fs";

const maxBlobBytes = 16 * 1024 * 1024;
const git = (args, options = {}) =>
  execFileSync("git", args, { maxBuffer: maxBlobBytes, ...options });
const expected = new Map();
for (const entry of git(["ls-tree", "-r", "-z", "HEAD", "--", "dist"]).toString().split("\0").filter(Boolean)) {
  const match = /^100(?:644|755) blob ([a-f0-9]+)\t(dist[/].+)$/.exec(entry);
  assert.ok(match, "Expected a regular committed dist file");
  expected.set(match[2], match[1]);
}
assert.ok(expected.size, "No committed dist files");

const blobs = new Map();
function collect(dir) {
  assert.ok(lstatSync(dir).isDirectory(), "Expected a real directory: " + dir);
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = dir + "/" + entry.name;
    if (entry.isDirectory()) { collect(file); continue; }
    const oid = expected.get(file);
    assert.ok(entry.isFile() && oid, "Unexpected dist entry: " + file);
    const size = lstatSync(file).size;
    assert.ok(size <= maxBlobBytes, "Generated file exceeds blob size limit: " + file);
    if (!blobs.has(oid)) blobs.set(oid, { size, files: [] });
    const blob = blobs.get(oid);
    assert.equal(size, blob.size, "Generated bytes differ: " + file);
    blob.files.push(file);
    expected.delete(file);
  }
}
collect("dist");
assert.equal(expected.size, 0, "Missing dist files: " + [...expected.keys()].join(", "));

// Batch replies are binary: header LF, exactly size bytes, then one LF.
// Bound output by the local sizes; a valid match cannot exceed this budget.
const data = git(["cat-file", "--batch"], {
  input: [...blobs.keys()].join("\n") + "\n",
  maxBuffer: [...blobs].reduce((total, [oid, { size }]) => total + size + oid.length + 32, 0),
});
let cursor = 0;
for (const [oid, { size, files }] of blobs) {
  const headerEnd = data.indexOf(0x0a, cursor);
  assert.ok(headerEnd !== -1, "Missing Git batch header: " + oid);
  const header = data.toString("ascii", cursor, headerEnd);
  const match = /^([a-f0-9]+) blob ([0-9]+)$/.exec(header);
  assert.ok(match && match[1] === oid, "Unexpected Git batch header for: " + files[0]);
  assert.equal(Number(match[2]), size, "Generated bytes differ: " + files[0]);
  const start = headerEnd + 1;
  cursor = start + size;
  assert.equal(data[cursor], 0x0a, "Invalid Git batch framing: " + oid);
  const bytes = data.subarray(start, cursor++);
  for (const file of files)
    assert.ok(readFileSync(file).equals(bytes), "Generated bytes differ: " + file);
}
assert.equal(cursor, data.length, "Unexpected trailing Git batch output");
console.log("Generated dist matches the committed paths and bytes");
